export function getCuratedWallpapers(
  query: string,
  mediaType: "image" | "video",
  page: number = 1,
  perPage: number = 10
): { hits: WallpaperHit[]; total: number; totalHits: number } {
  const normalizedQuery = (query || "anime").toLowerCase().trim();
  const searchTerms = normalizedQuery.split(/\s+/).filter(Boolean);

  let filtered = CURATED_ANIME_WALLPAPERS.filter((item) => {
    if (mediaType === "video") {
      return item.isVideo || item.type === "video";
    }
    return !item.isVideo && item.type !== "video";
  });

  if (searchTerms.length > 0 && normalizedQuery !== "anime") {
    const matched = filtered.filter((item) => {
      const target = `${item.tags} ${item.user}`.toLowerCase();
      return searchTerms.some((term) => target.includes(term));
    });
    if (matched.length > 0) {
      filtered = matched;
    }
  }

  const startIndex = (page - 1) * perPage;
  const paginatedHits = filtered.slice(startIndex, startIndex + perPage);

  // If beyond page bounds, loop gracefully
  const finalHits = paginatedHits.length > 0 ? paginatedHits : filtered.slice(0, perPage);

  return {
    hits: finalHits,
    total: filtered.length,
    totalHits: filtered.length
  };
}
